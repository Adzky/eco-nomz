CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    email VARCHAR(320) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(32) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_app_user_role CHECK (role IN ('CUSTOMER', 'RESTAURANT_OWNER', 'ADMIN'))
);

CREATE UNIQUE INDEX uq_app_user_email_lower ON app_user (LOWER(email));

CREATE TABLE restaurant (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES app_user (id),
    name VARCHAR(160) NOT NULL,
    description TEXT,
    address VARCHAR(500) NOT NULL,
    latitude NUMERIC(9, 6),
    longitude NUMERIC(9, 6),
    published BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_restaurant_latitude CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_restaurant_longitude CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180)
);

CREATE INDEX ix_restaurant_owner_id ON restaurant (owner_id);
CREATE INDEX ix_restaurant_published ON restaurant (published);

CREATE TABLE food_offer (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id BIGINT NOT NULL REFERENCES restaurant (id),
    title VARCHAR(160) NOT NULL,
    description TEXT,
    original_price NUMERIC(12, 2) NOT NULL,
    discounted_price NUMERIC(12, 2) NOT NULL,
    quantity_available INTEGER NOT NULL,
    pickup_start TIMESTAMP WITH TIME ZONE NOT NULL,
    pickup_end TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(32) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_food_offer_original_price CHECK (original_price > 0),
    CONSTRAINT ck_food_offer_discounted_price CHECK (
        discounted_price > 0 AND discounted_price < original_price
    ),
    CONSTRAINT ck_food_offer_quantity CHECK (quantity_available >= 0),
    CONSTRAINT ck_food_offer_pickup_window CHECK (pickup_end > pickup_start),
    CONSTRAINT ck_food_offer_status CHECK (status IN ('DRAFT', 'PUBLISHED', 'SOLD_OUT', 'EXPIRED'))
);

CREATE INDEX ix_food_offer_restaurant_id ON food_offer (restaurant_id);
CREATE INDEX ix_food_offer_status_pickup_end ON food_offer (status, pickup_end);

CREATE TABLE customer_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES app_user (id),
    food_offer_id BIGINT NOT NULL REFERENCES food_offer (id),
    quantity INTEGER NOT NULL,
    unit_price NUMERIC(12, 2) NOT NULL,
    total_price NUMERIC(12, 2) NOT NULL,
    status VARCHAR(32) NOT NULL,
    pickup_code VARCHAR(128) UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_customer_order_quantity CHECK (quantity > 0),
    CONSTRAINT ck_customer_order_unit_price CHECK (unit_price > 0),
    CONSTRAINT ck_customer_order_total_price CHECK (total_price > 0),
    CONSTRAINT ck_customer_order_status CHECK (
        status IN ('PENDING_PAYMENT', 'CONFIRMED', 'CANCELLED', 'COMPLETED', 'EXPIRED')
    )
);

CREATE INDEX ix_customer_order_customer_id ON customer_order (customer_id);
CREATE INDEX ix_customer_order_food_offer_id ON customer_order (food_offer_id);
CREATE INDEX ix_customer_order_status ON customer_order (status);

CREATE TABLE payment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL UNIQUE REFERENCES customer_order (id),
    provider_reference VARCHAR(255) UNIQUE,
    amount NUMERIC(12, 2) NOT NULL,
    status VARCHAR(32) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_payment_amount CHECK (amount > 0),
    CONSTRAINT ck_payment_status CHECK (
        status IN ('PENDING', 'SUCCEEDED', 'FAILED', 'REFUNDED')
    )
);
